create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.admin_profiles admin
    where admin.id = auth.uid()
      and admin.role = 'admin'
      and admin.is_active = true
  )
  or coalesce(auth.jwt() -> 'user_metadata' ->> 'role', '') = 'admin';
$$;

create policy "students can read own profile"
on public.students for select
using (id = auth.uid() or public.is_admin());

create policy "students can insert own profile or public lead profile"
on public.students for insert
with check (id = auth.uid() or id is not null);

create policy "students can update own profile"
on public.students for update
using (id = auth.uid() or public.is_admin())
with check (id = auth.uid() or public.is_admin());

create policy "students admin delete"
on public.students for delete
using (public.is_admin());

create policy "admins manage admin profiles"
on public.admin_profiles for all
using (public.is_admin())
with check (public.is_admin());

create policy "admins can read login activity"
on public.login_activity for select
